"""Data story stage: package only the evidence the story uses (ember-electricity).

Run from project root:  python -I workflow/analysis/build_story_data.py
Reads data/processed/findings.json and pressure-test.json (approved Original + Tested).
Writes site/data-story/assets/story-data.js and data/processed/story-data.json.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
P = ROOT / "data" / "processed"
F = json.loads((P / "findings.json").read_text(encoding="utf-8"))
T = json.loads((P / "pressure-test.json").read_text(encoding="utf-8"))
Y = F["yearly"]
L = F["latest"]
first = Y[0]

story = {
    "first": F["first"], "last": F["last"],
    # Scene 1 (C8): total generation per year
    "years": [r["year"] for r in Y],
    "total": [r["total"] for r in Y],
    "totalX": F["growth"]["totalX"],
    # Scene 2 (C2, C5): who met 2025's demand growth
    "dTotal": L["dTotal"], "dClean": L["dClean"], "dSolar": L["dSolar"], "dFossil": L["dFossil"],
    "solarShareOfGrowth": L["solarShareOfGrowth"], "cleanShareOfGrowth": L["cleanShareOfGrowth"],
    # Scene 3 (C1): share lines
    "renewShare": [r["renewShare"] for r in Y], "coalShare": [r["coalShare"] for r in Y],
    "coalPeak": F["peakCoalShareValue"], "coalPeakYear": F["peakCoalShare"],
    # Scene 4 (C1 qualification, T2): what renewables are made of
    "renew": T["renew"], "coal": T["coal"], "hydro": T["hydro"],
    "nonHydroShare": T["defs"]["nonHydroRenewShare"], "hydroShare": T["defs"]["hydroShare"],
    "windSolarShare": T["defs"]["windSolarShare"],
    # Scene 5 (C1 robustness)
    "margin": T["margin"], "kFlip": T["kFlip"], "dryFlips": T["dryFlips"],
    "gapPts": [{"year": r["year"], "pts": (r["renewShare"] - r["coalShare"]) * 100} for r in Y if r["year"] % 5 == 0],
    # Scene 6 (C9, C3, C7)
    "solar": [r["solar"] for r in Y], "solarX2015": F["growth"]["solarX2015"],
    "fossilPct": T["fossilPct"], "precedentYears": [p["year"] for p in T["precedents"] if p["year"] != F["last"]],
    # Redesign ("current" design guide): two currents, solar vs wind, mix bars
    "clean": [r["clean"] for r in Y], "fossil": [r["fossil"] for r in Y],
    "wind": [r["wind"] for r in Y], "dSolarTwh": L["dSolar"], "dWind": L["dWind"],
    "mix": F["mix"],
    "change": [{"s": a["source"], "d": a["d"]} for a in T["attrib"]],  # 2024 → 2025 TWh by source
    "gapLast": L["renewMinusCoalPts"],
}
(P / "story-data.json").write_text(json.dumps(story, indent=1), encoding="utf-8")
out = ROOT / "site" / "data-story" / "assets"
out.mkdir(parents=True, exist_ok=True)
(out / "story-data.js").write_text("/* Generated by workflow/analysis/build_story_data.py — do not edit. */\nwindow.STORY_DATA = "
                                   + json.dumps(story) + ";\n", encoding="utf-8")
print({k: story[k] for k in ["dTotal", "dClean", "solarShareOfGrowth", "margin", "kFlip", "nonHydroShare", "solarX2015", "precedentYears", "gapPts"]})
