"""Dashboard stage: package validated measures for site/dashboard (ember-electricity).

Run from project root:  python -I workflow/analysis/build_dashboard_data.py
Reads the raw CSV and data/processed/pressure-test.json. Writes site/dashboard/assets/dashboard-data.js
and data/processed/dashboard-data.json.
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "data" / "raw" / "ember_yearly_electricity-generation - All electricity sources - World - breakdown.csv"
T = json.loads((ROOT / "data" / "processed" / "pressure-test.json").read_text(encoding="utf-8"))
rows = list(csv.DictReader(RAW.open(encoding="utf-8-sig")))

FOSSIL = ["Coal", "Gas", "Other fossil"]
RENEW = ["Hydro", "Wind", "Solar", "Bioenergy", "Other renewables"]
SOURCES = FOSSIL + ["Nuclear"] + RENEW
GROUPS = {"Fossil": FOSSIL, "Renewables": RENEW, "Clean": RENEW + ["Nuclear"], "Wind + solar": ["Wind", "Solar"],
          "Renewables excl. hydro": ["Wind", "Solar", "Bioenergy", "Other renewables"]}

twh, kwh = {}, {}
for r in rows:
    y = int(r["date"])
    twh.setdefault(y, {})[r["series"]] = float(r["generation_twh"])
    kwh.setdefault(y, {})[r["series"]] = float(r["generation_kwh_per_capita"])
years = sorted(twh)

# Per-capita for groups: sum of members (kWh/person is additive across sources)
series = {}
for name in SOURCES + ["Total generation"]:
    series[name] = {"twh": [twh[y][name] for y in years], "kwh": [kwh[y][name] for y in years]}
for g, members in GROUPS.items():
    series[g] = {"twh": [sum(twh[y][m] for m in members) for y in years],
                 "kwh": [sum(kwh[y][m] for m in members) for y in years]}

# Comparison views (fixed colours per view: slot 1 purple, 2 orange, 3 mint; validated, all pairs pass)
views = [
    {"id": "renew-coal", "label": "Renewables vs coal", "series": ["Renewables", "Coal", "Renewables excl. hydro"]},
    {"id": "clean-fossil", "label": "Clean vs fossil", "series": ["Clean", "Fossil"]},
    {"id": "solar-wind", "label": "Solar, wind, hydro", "series": ["Solar", "Wind", "Hydro"]},
    {"id": "coal-gas-nuclear", "label": "Coal, gas, nuclear", "series": ["Nuclear", "Coal", "Gas"]},
]

measures = [
    {"name": "Generation", "formula": "generation_twh", "unit": "TWh", "caveat": "Electricity generated in the year; groups are sums of sources."},
    {"name": "Share of generation", "formula": "series TWh ÷ Total generation TWh", "unit": "%", "caveat": "Sources add to 100% within 0.02 pts."},
    {"name": "Per person", "formula": "generation_kwh_per_capita (groups: sum of sources)", "unit": "kWh per person", "caveat": "Uses Ember's population; world population is not in the file directly."},
    {"name": "Change vs comparison year", "formula": "value(year) − value(comparison year)", "unit": "TWh, pts or kWh", "caveat": "Comparison year must be earlier than the selected year."},
    {"name": "Renewables", "formula": "Hydro + Wind + Solar + Bioenergy + Other renewables", "unit": "—", "caveat": "Includes hydro, which swings with rainfall (s.d. 2.5% a year)."},
    {"name": "Clean", "formula": "Renewables + Nuclear", "unit": "—", "caveat": "Ember's low-carbon grouping."},
    {"name": "Fossil", "formula": "Coal + Gas + Other fossil", "unit": "—", "caveat": "Not an emissions measure."},
    {"name": "Latest year", "formula": "2025", "unit": "—", "caveat": f"Finality not stated; the renewables-over-coal lead ({T['margin']:.0f} TWh) is undone by a {T['kFlip'] * 100:.2f}% opposite revision."},
]

out = {"years": years, "sources": SOURCES, "groups": GROUPS, "series": series, "views": views, "measures": measures,
       "latest": years[-1], "margin": T["margin"], "kFlip": T["kFlip"]}
(ROOT / "data" / "processed" / "dashboard-data.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
site = ROOT / "site" / "dashboard" / "assets"
site.mkdir(parents=True, exist_ok=True)
(site / "dashboard-data.js").write_text("/* Generated by workflow/analysis/build_dashboard_data.py — do not edit. */\nwindow.DASH_DATA = "
                                        + json.dumps(out) + ";\n", encoding="utf-8")
print(len(years), "years;", len(series), "series;", len(views), "views; check renew 2025 share",
      round(series["Renewables"]["twh"][-1] / series["Total generation"]["twh"][-1] * 100, 2))
