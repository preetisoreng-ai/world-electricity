/* Tested stage (ember-electricity): renders from window.TESTED_DATA,
   generated by workflow/analysis/pressure_test.py. No numbers typed by hand. */
(() => {
  const T = window.TESTED_DATA;
  const $ = (s, c = document) => c.querySelector(s);
  const NS = "http://www.w3.org/2000/svg";
  const svgEl = (tag, attrs = {}, text) => {
    const el = document.createElementNS(NS, tag);
    for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, v);
    if (text != null) el.textContent = text;
    return el;
  };
  const esc = (s) =>
    String(s).replace(
      /[&<>"]/g,
      (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]
    );
  const n0 = (v) => Math.round(v).toLocaleString("en-US");
  const pct = (v, d = 1) => (v < 0 ? "−" : "") + (Math.abs(v) * 100).toFixed(d) + "%";
  const sgn = (v) => (v >= 0 ? "+" : "−") + n0(Math.abs(v));

  if (!T) {
    document.querySelectorAll(".chart-card, .checks-scroll").forEach((c) => {
      const p = document.createElement("p");
      p.className = "empty";
      p.textContent =
        "Data file assets/tested-data.js did not load. Re-run python -I workflow/analysis/pressure_test.py.";
      c.append(p);
    });
    return;
  }

  /* ---------- Bound text ---------- */
  const binds = {
    margin: n0(T.margin) + " TWh",
    kFlip: pct(T.kFlip, 2),
    nonHydro: pct(T.defs.nonHydroRenewShare),
    fossilPct: pct(T.fossilPct, 2),
    hydroShare: pct(T.defs.hydroShare),
    dryFlips: T.dryFlips.join(", "),
    hydro2025: pct(T.hydro2025Pct),
    coalMax: String(T.coalMaxYear),
    windSolar: pct(T.defs.windSolarShare),
    recompute: "14 of 14",
  };
  document.querySelectorAll("[data-bind]").forEach((el) => {
    const v = binds[el.dataset.bind];
    if (v != null) el.textContent = v;
  });
  $("#verdictSummary").textContent = ["verified", "qualified", "revised", "rejected"]
    .filter((s) => T.statusCounts[s])
    .map((s) => `${T.statusCounts[s]} ${s}`)
    .join(" · ");

  /* ---------- Tables ---------- */
  $("#claimRows").innerHTML = T.claims
    .map(
      (c) =>
        `<tr><td>${esc(c.original)}</td><td><span class="status ${c.status}">${c.status[0].toUpperCase() + c.status.slice(1)}</span></td><td>${esc(c.found)}</td><td>${esc(c.use)}</td></tr>`
    )
    .join("");
  $("#checkRows").innerHTML = T.checks
    .map(
      (c) => `<tr><td>${esc(c.check)}</td><td>${esc(c.result)}</td><td>${esc(c.effect)}</td></tr>`
    )
    .join("");

  /* ---------- Revision slider ---------- */
  const slider = $("#kSlider");
  const maxV = Math.max(...T.revision.map((r) => Math.max(r.renew, r.coal)));
  function update() {
    const r = T.revision[Number(slider.value)];
    $("#kOut").textContent = (r.k * 100).toFixed(1) + "%";
    $("#pbRenew").style.setProperty("--w", ((r.renew / maxV) * 100).toFixed(2) + "%");
    $("#pbCoal").style.setProperty("--w", ((r.coal / maxV) * 100).toFixed(2) + "%");
    $("#pbRenewV").textContent = n0(r.renew) + " TWh";
    $("#pbCoalV").textContent = n0(r.coal) + " TWh";
    const holds = r.margin > 0;
    $("#kRead").innerHTML =
      `Renewables ${holds ? "still lead" : "fall behind"} by <strong>${n0(Math.abs(r.margin))} TWh</strong>. <span class="verdict ${holds ? "holds" : "fails"}">${holds ? "Crossover holds" : "Crossover undone"}</span>`;
  }
  slider.addEventListener("input", update);
  update();

  /* ---------- Stacked composition ---------- */
  (() => {
    const svg = $("#stackChart");
    const W = 520,
      m = { l: 96, r: 70 },
      max = 0.36;
    const x = (v) => m.l + (v / max) * (W - m.l - m.r);
    const d = T.defs;
    const row = (yy, label) =>
      svg.append(
        svgEl(
          "text",
          { class: "stack-label", x: m.l - 10, y: yy + 26, "text-anchor": "end" },
          label
        )
      );
    row(30, "Renewables");
    svg.append(
      svgEl("rect", { class: "stack-a", x: x(0), y: 30, width: x(d.hydroShare) - x(0), height: 40 })
    );
    svg.append(
      svgEl("rect", {
        class: "stack-a2",
        x: x(d.hydroShare) + 2,
        y: 30,
        width: x(d.renewShare) - x(d.hydroShare) - 2,
        height: 40,
      })
    );
    svg.append(
      svgEl("text", { class: "stack-label in", x: x(0) + 8, y: 56 }, `Hydro ${pct(d.hydroShare)}`)
    );
    svg.append(
      svgEl(
        "text",
        { class: "stack-label", x: x(d.hydroShare) + 10, y: 56 },
        `Other ${pct(d.nonHydroRenewShare)}`
      )
    );
    svg.append(
      svgEl("text", { class: "stack-label", x: x(d.renewShare) + 8, y: 56 }, pct(d.renewShare))
    );
    row(110, "Coal");
    svg.append(
      svgEl("rect", { class: "stack-b", x: x(0), y: 110, width: x(d.coalShare) - x(0), height: 40 })
    );
    svg.append(
      svgEl("text", { class: "stack-label", x: x(d.coalShare) + 8, y: 136 }, pct(d.coalShare))
    );
    // Reference: non-hydro renewables against coal
    svg.append(
      svgEl("line", {
        class: "annot-line",
        x1: x(d.renewShare),
        x2: x(d.renewShare),
        y1: 22,
        y2: 160,
      })
    );
    svg.append(
      svgEl(
        "text",
        { class: "axis-label", x: m.l, y: 196 },
        `Without hydro, renewables are ${pct(d.nonHydroRenewShare)}: ${pct(d.coalShare - d.nonHydroRenewShare)} points behind coal.`
      )
    );
  })();

  /* ---------- Tooltip helper ---------- */
  function placeTip(tip, svg, vbW, x, y, html) {
    const host = tip.parentElement.getBoundingClientRect(),
      sr = svg.getBoundingClientRect(),
      k = sr.width / vbW;
    tip.innerHTML = html;
    tip.hidden = false;
    tip.style.left = Math.min(Math.max(x * k + sr.left - host.left, 110), host.width - 110) + "px";
    tip.style.top = y * k + sr.top - host.top + "px";
  }

  /* ---------- Generic vertical bars around zero ---------- */
  function zeroBars({
    svg,
    tip,
    W,
    H,
    m,
    data,
    value,
    cls,
    label,
    tickEvery,
    html,
    aria,
    outline,
  }) {
    const vals = data.map(value);
    const step = tickEvery;
    const lo = Math.min(0, Math.floor(Math.min(...vals) / step) * step),
      hi = Math.ceil(Math.max(...vals) / step) * step;
    const band = (W - m.l - m.r) / data.length;
    const y = (v) => m.t + ((hi - v) / (hi - lo)) * (H - m.t - m.b);
    for (let v = lo; v <= hi; v += step) {
      svg.append(
        svgEl("line", {
          class: v === 0 ? "zero-line" : "grid-line",
          x1: m.l,
          x2: W - m.r,
          y1: y(v),
          y2: y(v),
        })
      );
      svg.append(
        svgEl(
          "text",
          { class: "axis-label", x: m.l - 8, y: y(v) + 4, "text-anchor": "end" },
          (v > 0 ? "+" : v < 0 ? "−" : "") + n0(Math.abs(v))
        )
      );
    }
    data.forEach((d, i) => {
      const v = value(d),
        x0 = m.l + i * band;
      const top = Math.min(y(v), y(0)),
        h = Math.max(1, Math.abs(y(v) - y(0)));
      svg.append(
        svgEl("rect", {
          class: cls(d) + (outline && outline(d) ? " bar-actual" : ""),
          x: x0 + 2,
          y: top,
          width: Math.max(2, band - 4),
          height: h,
          rx: 2,
        })
      );
      if (label(d))
        svg.append(
          svgEl(
            "text",
            { class: "axis-label", x: x0 + band / 2, y: H - m.b + 18, "text-anchor": "middle" },
            label(d)
          )
        );
      const hit = svgEl("rect", {
        class: "hit",
        x: x0,
        y: m.t,
        width: band,
        height: H - m.t - m.b,
        tabindex: 0,
        "aria-label": aria(d),
      });
      const show = () => placeTip(tip, svg, W, x0 + band / 2, Math.min(y(v), y(0)), html(d));
      hit.addEventListener("mouseenter", show);
      hit.addEventListener("focus", show);
      hit.addEventListener("mouseleave", () => (tip.hidden = true));
      hit.addEventListener("blur", () => (tip.hidden = true));
      svg.append(hit);
    });
  }

  zeroBars({
    svg: $("#dryChart"),
    tip: $("#dryTip"),
    W: 520,
    H: 260,
    m: { t: 14, r: 10, b: 30, l: 50 },
    data: T.dry,
    value: (d) => d.margin,
    tickEvery: 100,
    cls: (d) => (d.flips ? "bar-fail" : "bar-hold"),
    outline: (d) => d.year === T.last,
    label: (d) => (d.year % 5 === 0 || d.year === 2001 ? String(d.year) : ""),
    html: (d) =>
      `<b>Hydro like ${d.year} (${pct(d.pct)})</b>Renewables ${d.margin >= 0 ? "ahead" : "behind"} by ${n0(Math.abs(d.margin))} TWh`,
    aria: (d) =>
      `With a hydro change like ${d.year}, ${pct(d.pct)}: renewables ${d.margin >= 0 ? "ahead of" : "behind"} coal by ${n0(Math.abs(d.margin))} TWh`,
  });

  const precYears = new Set(T.precedents.map((p) => p.year));
  zeroBars({
    svg: $("#coalChart"),
    tip: $("#coalTip"),
    W: 760,
    H: 320,
    m: { t: 14, r: 10, b: 30, l: 56 },
    data: T.coalYoy,
    value: (d) => d.d,
    tickEvery: 200,
    cls: (d) => (precYears.has(d.year) ? "bar-b" : "bar-b bar-dim"),
    label: (d) => (d.year % 5 === 0 || d.year === 2001 ? String(d.year) : ""),
    html: (d) => `<b>${d.year}</b>Coal ${sgn(d.d)} TWh · demand ${sgn(d.dDemand)} TWh`,
    aria: (d) => `${d.year}: coal ${sgn(d.d)} TWh, demand ${sgn(d.dDemand)} TWh`,
  });

  document.querySelectorAll(".chart-wrap.scroll").forEach((w) => (w.scrollLeft = w.scrollWidth));
  if (window.upiMotion) window.upiMotion.ready();
})();
