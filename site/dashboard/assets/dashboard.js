/* Dashboard stage (ember-electricity): renders from window.DASH_DATA,
   generated by workflow/analysis/build_dashboard_data.py. */
(() => {
  const D = window.DASH_DATA;
  const $ = (s, c = document) => c.querySelector(s);
  const $$ = (s, c = document) => [...c.querySelectorAll(s)];
  const NS = "http://www.w3.org/2000/svg";
  const svgEl = (tag, attrs = {}, text) => {
    const el = document.createElementNS(NS, tag);
    for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, v);
    if (text != null) el.textContent = text;
    return el;
  };
  const MINUS = "−";
  const n0 = (v) => Math.round(v).toLocaleString("en-US");

  if (!D) {
    $("#loadError").hidden = false;
    $(".kpis").setAttribute("aria-busy", "false");
    $$(".kpi strong").forEach((s) => (s.textContent = "—"));
    return;
  }

  const Y = D.years,
    LAST = D.latest;
  const yi = (y) => Y.indexOf(y);
  const total = D.series["Total generation"].twh;
  /* value(series, yearIndex, measure) */
  function val(name, i, m) {
    const s = D.series[name];
    if (m === "twh") return s.twh[i];
    if (m === "kwh") return s.kwh[i];
    return (s.twh[i] / total[i]) * 100;
  }
  const UNIT = { share: "%", twh: " TWh", kwh: " kWh" };
  const UNIT_D = { share: " pts", twh: " TWh", kwh: " kWh" };
  function fmt(v, m) {
    if (m === "share") return v.toFixed(1) + "%";
    if (m === "kwh") return n0(v) + " kWh";
    return n0(v) + " TWh";
  }
  function fmtD(v, m) {
    const a = Math.abs(v);
    const shown = m === "share" ? +a.toFixed(1) : Math.round(a);
    const sgn = shown === 0 ? "±" : v > 0 ? "+" : MINUS;
    return sgn + (m === "share" ? a.toFixed(1) : n0(a)) + UNIT_D[m];
  }
  const MLABEL = {
    share: "Share of world generation, %",
    twh: "Generation, TWh",
    kwh: "Generation per person, kWh",
  };

  const DEFAULT = { year: LAST, base: LAST - 1, measure: "share", view: "renew-coal" };
  const state = { ...DEFAULT };

  /* ---------- Controls ---------- */
  const yearSel = $("#yearSel"),
    baseSel = $("#baseSel"),
    measureSel = $("#measureSel");
  [...Y]
    .reverse()
    .forEach((y) => yearSel.add(new Option(y === LAST ? `${y} (latest)` : String(y), y)));
  function fillBase() {
    baseSel.innerHTML = "";
    // Only earlier years are valid comparisons
    const valid = Y.filter((y) => y < state.year);
    [...valid].reverse().forEach((y) => baseSel.add(new Option(String(y), y)));
    // Keep the comparison year only if it is a real, earlier year; otherwise use the year before
    if (!valid.includes(state.base)) state.base = valid.length ? valid.at(-1) : null;
    baseSel.disabled = !baseSel.options.length;
    if (!baseSel.options.length) baseSel.add(new Option("No earlier year", ""));
  }
  function sync() {
    yearSel.value = state.year;
    fillBase();
    if (!baseSel.disabled) baseSel.value = state.base;
    measureSel.value = state.measure;
    $$("#viewTabs button").forEach((b) =>
      b.setAttribute("aria-pressed", b.dataset.view === state.view)
    );
  }
  yearSel.addEventListener("change", () => {
    state.year = +yearSel.value;
    sync();
    render();
  });
  baseSel.addEventListener("change", () => {
    state.base = +baseSel.value;
    render();
  });
  measureSel.addEventListener("change", () => {
    state.measure = measureSel.value;
    render();
  });
  $("#reset").addEventListener("click", () => {
    Object.assign(state, DEFAULT);
    sync();
    render();
  });

  const vt = $("#viewTabs");
  D.views.forEach((v) => {
    const b = document.createElement("button");
    b.type = "button";
    b.dataset.view = v.id;
    b.textContent = v.label;
    b.addEventListener("click", () => {
      state.view = v.id;
      sync();
      render();
    });
    vt.append(b);
  });

  /* ---------- Page tabs ---------- */
  const tabs = $$('[role="tab"]');
  function selectTab(tab) {
    tabs.forEach((t) => {
      const on = t === tab;
      t.setAttribute("aria-selected", on);
      t.tabIndex = on ? 0 : -1;
      $("#" + t.getAttribute("aria-controls")).hidden = !on;
    });
    $(".filters").hidden = tab.id === "tab-defs";
  }
  tabs.forEach((t, i) => {
    t.addEventListener("click", () => selectTab(t));
    t.addEventListener("keydown", (ev) => {
      const d = ev.key === "ArrowRight" ? 1 : ev.key === "ArrowLeft" ? -1 : 0;
      if (!d) return;
      const n = tabs[(i + d + tabs.length) % tabs.length];
      n.focus();
      selectTab(n);
    });
  });

  /* ---------- Render ---------- */
  function render() {
    const m = state.measure,
      i = yi(state.year),
      b = baseSel.disabled ? null : yi(state.base);
    const parts = [];
    if (state.year !== DEFAULT.year) parts.push(String(state.year));
    if (!baseSel.disabled && state.base !== DEFAULT.base) parts.push("vs " + state.base);
    if (state.measure !== DEFAULT.measure) parts.push(measureSel.selectedOptions[0].textContent);
    if (state.view !== DEFAULT.view) parts.push(D.views.find((v) => v.id === state.view).label);
    $("#filterState").textContent = parts.length
      ? "Changed: " + parts.join(" · ")
      : "Showing defaults";
    $("#reset").disabled = !parts.length;

    // KPIs
    $(".kpis").setAttribute("aria-busy", "false");
    [
      ["Renewables", "Renew"],
      ["Coal", "Coal"],
      ["Clean", "Clean"],
      ["Fossil", "Fossil"],
    ].forEach(([name, id]) => {
      const v = val(name, i, m);
      $("#k" + id).textContent = fmt(v, m);
      const dEl = $("#d" + id);
      if (b == null) {
        dEl.textContent = "";
        dEl.className = "delta";
      } else {
        const d = v - val(name, b, m);
        dEl.textContent = `${fmtD(d, m)} vs ${state.base}`;
        dEl.className = "delta " + (Math.abs(d) < 0.05 ? "flat" : d > 0 ? "up" : "down");
      }
      const share = val(name, i, "share");
      $("#s" + id).innerHTML =
        (m === "share" ? `${n0(val(name, i, "twh"))} TWh` : `${share.toFixed(1)}% of generation`) +
        (state.year === LAST ? ' <span class="revise">may be revised</span>' : "");
    });

    renderTrend();
    renderChange(i, b);
    renderMix(i, b);
    renderTable();
    const crossNote =
      state.year === LAST && m !== "kwh"
        ? ` In ${LAST}, renewables’ lead over coal (${n0(D.margin)} TWh) would be undone by a ${(D.kFlip * 100).toFixed(2)}% opposite revision.`
        : "";
    $("#noticeText").textContent =
      "World totals only. Renewables include hydro, which swings with rainfall (s.d. 2.5% a year)." +
      crossNote;
  }

  /* ---------- Trend ---------- */
  function renderTrend() {
    const m = state.measure,
      view = D.views.find((v) => v.id === state.view);
    const svg = $("#trendChart");
    svg.querySelectorAll(":not(desc)").forEach((n) => n.remove());
    const W = 900,
      H = 340,
      mg = { t: 16, r: 190, b: 32, l: 56 };
    const all = view.series.flatMap((s) => Y.map((_, k) => val(s, k, m)));
    const raw = Math.max(...all);
    const step = m === "share" ? 10 : raw > 8000 ? 5000 : raw > 3000 ? 1000 : raw > 800 ? 200 : 100;
    const hi = Math.ceil(raw / step) * step;
    const x = (k) => mg.l + (k / (Y.length - 1)) * (W - mg.l - mg.r);
    const y = (v) => mg.t + (1 - v / hi) * (H - mg.t - mg.b);
    for (let v = 0; v <= hi; v += step) {
      svg.append(svgEl("line", { class: "grid-line", x1: mg.l, x2: W - mg.r, y1: y(v), y2: y(v) }));
      svg.append(
        svgEl(
          "text",
          { class: "axis-label", x: mg.l - 8, y: y(v) + 4, "text-anchor": "end" },
          m === "share" ? v + "%" : n0(v)
        )
      );
    }
    Y.forEach((yr, k) => {
      if (yr % 5 === 0)
        svg.append(
          svgEl(
            "text",
            { class: "axis-label", x: x(k), y: H - mg.b + 20, "text-anchor": "middle" },
            yr
          )
        );
    });
    // Year markers
    [[state.year, "selected"], baseSel.disabled ? null : [state.base, "comparison"]]
      .filter(Boolean)
      .forEach(([yr, lab]) => {
        const xx = x(yi(yr));
        svg.append(svgEl("line", { class: "yr-mark", x1: xx, x2: xx, y1: mg.t, y2: H - mg.b }));
        // Labels sit left of their line; the comparison label drops a line so adjacent years never collide
        svg.append(
          svgEl(
            "text",
            {
              class: "yr-tag",
              x: xx - 4,
              y: mg.t + (lab === "selected" ? 10 : 24),
              "text-anchor": "end",
            },
            `${yr} ${lab}`
          )
        );
      });
    // Lines + end labels (de-collided)
    const ends = [];
    view.series.forEach((s, si) => {
      const pts = Y.map((_, k) => `${x(k).toFixed(1)},${y(val(s, k, m)).toFixed(1)}`).join(" ");
      svg.append(svgEl("polyline", { class: `ln s${si + 1}`, points: pts }));
      ends.push({ s, si, y: y(val(s, Y.length - 1, m)), v: val(s, Y.length - 1, m) });
    });
    ends.sort((a, b2) => a.y - b2.y);
    for (let k = 1; k < ends.length; k++)
      if (ends[k].y - ends[k - 1].y < 15) ends[k].y = ends[k - 1].y + 15;
    ends.forEach((e) =>
      svg.append(
        svgEl("text", { class: "end-lab", x: W - mg.r + 8, y: e.y + 4 }, `${e.s} ${fmt(e.v, m)}`)
      )
    );
    $("#trendTitle").textContent = view.label;
    $("#trendSub").textContent = `${MLABEL[m]}, ${Y[0]}–${LAST}`;
    $("#trendLegend").innerHTML =
      view.series.map((s, si) => `<span><span class="key s${si + 1}"></span>${s}</span>`).join("") +
      '<span><span class="swatch dash"></span>Selected / comparison year</span>';
    $("#trendDesc").textContent =
      `Line chart, ${MLABEL[m]}: ` +
      view.series
        .map(
          (s) =>
            `${s} ${fmt(val(s, 0, m), m)} in ${Y[0]} to ${fmt(val(s, Y.length - 1, m), m)} in ${LAST}`
        )
        .join("; ") +
      ".";
    // Crosshair (mouse + keyboard)
    const tip = $("#tip");
    const hover = svgEl("g", { visibility: "hidden" });
    const hl = svgEl("line", { class: "hover-line", y1: mg.t, y2: H - mg.b });
    hover.append(hl);
    const dots = view.series.map((_, si) => {
      const c = svgEl("circle", { r: 4.5, class: `pt s${si + 1}` });
      hover.append(c);
      return c;
    });
    svg.append(hover);
    const hit = svgEl("rect", {
      class: "hit",
      x: mg.l,
      y: mg.t,
      width: W - mg.l - mg.r,
      height: H - mg.t - mg.b,
      tabindex: 0,
      "aria-label": "Trend values: use left and right arrow keys to move between years",
    });
    svg.append(hit);
    let cur = yi(state.year);
    const show = (k) => {
      cur = Math.max(0, Math.min(Y.length - 1, k));
      const xx = x(cur);
      hover.setAttribute("visibility", "visible");
      hl.setAttribute("x1", xx);
      hl.setAttribute("x2", xx);
      view.series.forEach((s, si) => {
        dots[si].setAttribute("cx", xx);
        dots[si].setAttribute("cy", y(val(s, cur, m)));
      });
      const host = tip.parentElement.getBoundingClientRect(),
        sr = svg.getBoundingClientRect(),
        sc = sr.width / W;
      tip.innerHTML =
        `<b>${Y[cur]}</b>` + view.series.map((s) => `${s} ${fmt(val(s, cur, m), m)}`).join(" · ");
      tip.hidden = false;
      tip.style.left =
        Math.min(Math.max(xx * sc + sr.left - host.left, 160), host.width - 160) + "px";
      tip.style.top =
        Math.min(...view.series.map((s) => y(val(s, cur, m)))) * sc + sr.top - host.top + "px";
    };
    const hide = () => {
      hover.setAttribute("visibility", "hidden");
      tip.hidden = true;
    };
    hit.addEventListener("mousemove", (ev) => {
      const sr = svg.getBoundingClientRect();
      show(
        Math.round(
          ((((ev.clientX - sr.left) / sr.width) * W - mg.l) / (W - mg.l - mg.r)) * (Y.length - 1)
        )
      );
    });
    hit.addEventListener("mouseleave", hide);
    hit.addEventListener("focus", () => show(cur));
    hit.addEventListener("blur", hide);
    hit.addEventListener("keydown", (ev) => {
      if (ev.key !== "ArrowLeft" && ev.key !== "ArrowRight") return;
      ev.preventDefault();
      show(cur + (ev.key === "ArrowRight" ? 1 : -1));
    });
  }

  /* ---------- Change by source ---------- */
  function renderChange(i, b) {
    const m = state.measure,
      svg = $("#changeChart");
    svg.querySelectorAll(":not(desc)").forEach((n) => n.remove());
    if (b == null) {
      svg.append(
        svgEl(
          "text",
          { class: "bar-lab", x: 260, y: 160, "text-anchor": "middle" },
          "Pick an earlier comparison year to see changes."
        )
      );
      $("#changeTitle").textContent = "Change by source";
      $("#changeDesc").textContent = `No comparison: ${state.year} is the first year in the data.`;
      return;
    }
    const rows = D.sources
      .map((s) => ({ s, d: val(s, i, m) - val(s, b, m) }))
      .sort((p, q) => q.d - p.d);
    const W = 520,
      H = 330,
      mg = { t: 8, r: 70, b: 8, l: 120 };
    const max = Math.max(...rows.map((r) => Math.abs(r.d))) || 1;
    const lo = Math.min(0, ...rows.map((r) => r.d)),
      hi = Math.max(0, ...rows.map((r) => r.d));
    const span = hi - lo || 1;
    const x = (v) => mg.l + ((v - lo) / span) * (W - mg.l - mg.r);
    const rh = (H - mg.t - mg.b) / rows.length;
    svg.append(svgEl("line", { class: "zero-line", x1: x(0), x2: x(0), y1: mg.t, y2: H - mg.b }));
    rows.forEach((r, k) => {
      const yy = mg.t + k * rh;
      svg.append(
        svgEl(
          "text",
          { class: "bar-lab", x: mg.l - 8, y: yy + rh / 2 + 4, "text-anchor": "end" },
          r.s
        )
      );
      const x0 = Math.min(x(0), x(r.d)),
        w = Math.max(1, Math.abs(x(r.d) - x(0)));
      const rect = svgEl("rect", {
        class: r.d >= 0 ? "bar-up" : "bar-down",
        x: x0,
        y: yy + 5,
        width: w,
        height: rh - 10,
        rx: 3,
      });
      rect.append(svgEl("title", {}, `${r.s}: ${fmtD(r.d, m)}`));
      svg.append(rect);
      svg.append(
        svgEl(
          "text",
          {
            // Negative values are labelled just right of the zero line so they never run into the source names
            class: "bar-val",
            x: r.d >= 0 ? x(r.d) + 6 : x(0) + 6,
            y: yy + rh / 2 + 4,
            "text-anchor": "start",
          },
          fmtD(r.d, m)
        )
      );
    });
    void max;
    $("#changeTitle").textContent = `Change by source, ${state.base} → ${state.year}`;
    $("#changeSub").textContent =
      m === "share"
        ? "Percentage points of world generation (sums to zero)"
        : m === "twh"
          ? "TWh"
          : "kWh per person";
    $("#changeDesc").textContent =
      "Change by source: " + rows.map((r) => `${r.s} ${fmtD(r.d, m)}`).join(", ") + ".";
  }

  /* ---------- Mix dumbbells (always shares) ---------- */
  function renderMix(i, b) {
    const host = $("#mixRows");
    host.innerHTML = "";
    const bi = b == null ? i : b;
    const rows = D.sources
      .map((s) => ({ s, a: val(s, bi, "share"), z: val(s, i, "share") }))
      .sort((p, q) => q.z - p.z);
    const max = Math.max(...rows.flatMap((r) => [r.a, r.z]));
    const sx = (v) => ((v / max) * 100).toFixed(2) + "%";
    rows.forEach((r) => {
      const up = r.z >= r.a;
      const el = document.createElement("div");
      el.className = "db " + (up ? "up" : "down");
      el.setAttribute("role", "listitem");
      el.setAttribute(
        "aria-label",
        `${r.s}: ${r.a.toFixed(1)}% in ${Y[bi]}, ${r.z.toFixed(1)}% in ${state.year}`
      );
      const l = Math.min(r.a, r.z),
        h = Math.max(r.a, r.z);
      el.innerHTML = `<span>${r.s}</span><span class="rail" aria-hidden="true"><span class="seg" style="left:${sx(l)};width:calc(${sx(h)} - ${sx(l)})"></span><span class="dot" style="left:${sx(r.a)}"></span><span class="end" style="left:${sx(r.z)}"></span></span><span class="nums">${r.a.toFixed(1)}% → <b>${r.z.toFixed(1)}%</b></span>`;
      host.append(el);
    });
    $("#mixTitle").textContent = b == null ? `Mix, ${state.year}` : `Mix, ${Y[bi]} → ${state.year}`;
  }

  /* ---------- Table ---------- */
  const COLS = [
    "Coal",
    "Gas",
    "Other fossil",
    "Nuclear",
    "Hydro",
    "Wind",
    "Solar",
    "Bioenergy",
    "Other renewables",
    "Renewables",
    "Clean",
    "Fossil",
    "Total generation",
  ];
  function renderTable() {
    const m = state.measure;
    $("#thead").innerHTML =
      `<tr><th scope="col">Year</th>${COLS.map((c) => `<th scope="col" class="num">${c}</th>`).join("")}</tr>`;
    $("#tbody").innerHTML = [...Y]
      .reverse()
      .map((yr) => {
        const k = yi(yr);
        const cls = yr === state.year ? "focus" : "";
        return `<tr class="${cls}"><td>${yr}${yr === LAST ? ' <span class="revise">may be revised</span>' : ""}</td>${COLS.map((c) => `<td class="num">${m === "share" ? val(c, k, m).toFixed(2) : val(c, k, m).toFixed(m === "twh" ? 1 : 0)}</td>`).join("")}</tr>`;
      })
      .join("");
    $("#tableNote").textContent =
      `${MLABEL[m]} · ${Y.length} years × ${COLS.length} series · selected year highlighted`;
  }
  $("#dlTable").addEventListener("click", () => {
    const m = state.measure;
    const lines = [
      ["year", ...COLS.map((c) => c.toLowerCase().replace(/ /g, "_"))].join(",") + "," + "measure",
    ];
    Y.forEach((yr, k) =>
      lines.push([yr, ...COLS.map((c) => val(c, k, m).toFixed(4))].join(",") + "," + m)
    );
    const url = URL.createObjectURL(new Blob([lines.join("\n") + "\n"], { type: "text/csv" }));
    const a = Object.assign(document.createElement("a"), {
      href: url,
      download: `ember-world-generation-${m}.csv`,
    });
    document.body.append(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  });

  /* ---------- Definitions ---------- */
  const esc = (s) =>
    String(s).replace(
      /[&<>"]/g,
      (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]
    );
  $("#defRows").innerHTML = D.measures
    .map(
      (d) =>
        `<tr><td>${esc(d.name)}</td><td><code>${esc(d.formula)}</code></td><td>${esc(d.unit)}</td><td>${esc(d.caveat)}</td></tr>`
    )
    .join("");

  sync();
  render();
  document.querySelectorAll(".chart-wrap.scroll").forEach((w) => (w.scrollLeft = w.scrollWidth));
  if (window.upiMotion) window.upiMotion.ready();
})();
