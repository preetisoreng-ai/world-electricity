/* Original stage (ember-electricity): renders from window.ORIGINAL_DATA,
   generated by workflow/analysis/profile_and_analyse.py. No numbers typed by hand. */
(() => {
  const D = window.ORIGINAL_DATA;
  const $ = (s, c = document) => c.querySelector(s);
  const NS = "http://www.w3.org/2000/svg";
  const svgEl = (tag, attrs = {}, text) => {
    const el = document.createElementNS(NS, tag);
    for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, v);
    if (text != null) el.textContent = text;
    return el;
  };
  const n0 = (v) => Math.round(v).toLocaleString("en-US");
  const pct = (v, d = 1) => (v * 100).toFixed(d) + "%";
  const sgn = (v) => (v >= 0 ? "+" : "−") + n0(Math.abs(v));

  if (!D) {
    document.querySelectorAll(".chart-card").forEach((c) => {
      const p = document.createElement("p");
      p.className = "empty";
      p.textContent =
        "Data file assets/original-data.js did not load. Re-run python -I workflow/analysis/profile_and_analyse.py.";
      c.append(p);
    });
    return;
  }

  const L = D.latest,
    Y = D.yearly;
  const byYear = Object.fromEntries(Y.map((r) => [r.year, r]));
  const covers = D.cleanCoversGrowthYears.filter((y) => y !== D.last);

  /* ---------- Bound text ---------- */
  const binds = {
    renew: pct(L.renewShare),
    coal: pct(L.coalShare),
    dClean: n0(L.dClean) + " TWh",
    dTotal: n0(L.dTotal) + " TWh",
    dFossilAbs: n0(Math.abs(L.dFossil)) + " TWh",
    renewVsCoal: `${pct(L.renewShare)} vs ${pct(L.coalShare)}`,
    solarGrowth: pct(L.solarShareOfGrowth, 0),
    fossilShare: pct(L.fossilShare),
    coalPeak: pct(D.peakCoalShareValue),
    coalPeakYear: String(D.peakCoalShare),
    gap: L.renewMinusCoalPts.toFixed(1),
    coverYears: covers.join(" and "),
    coverDemand: covers.map((y) => n0(byYear[y].dTotal)).join(" and ") + " TWh",
    dSolar: n0(L.dSolar) + " TWh",
    solar: n0(L.solar) + " TWh",
    wind: n0(L.wind) + " TWh",
    solarX: String(Math.round(D.growth.solarX2015)),
    total2000: n0(D.base.total),
    total2025: n0(L.total),
  };
  document.querySelectorAll("[data-bind]").forEach((el) => {
    const v = binds[el.dataset.bind];
    if (v != null) el.textContent = v;
  });

  /* ---------- Shared tooltip helper (positions inside .chart-wrap) ---------- */
  function placeTip(tip, svg, vbW, x, y, html) {
    const host = tip.parentElement.getBoundingClientRect();
    const sr = svg.getBoundingClientRect();
    const k = sr.width / vbW;
    tip.innerHTML = html;
    tip.hidden = false;
    tip.style.left = Math.min(Math.max(x * k + sr.left - host.left, 100), host.width - 100) + "px";
    tip.style.top = y * k + sr.top - host.top + "px";
  }

  /* ---------- Generic line chart with crosshair ---------- */
  function lineChart({ svg, tip, W, H, m, a, b, yMax, yTicks, fmtY, labels, tipHtml, onDraw }) {
    const years = Y.map((r) => r.year);
    const x = (yr) => m.l + ((yr - years[0]) / (years.at(-1) - years[0])) * (W - m.l - m.r);
    const y = (v) => m.t + (1 - v / yMax) * (H - m.t - m.b);
    yTicks.forEach((v) => {
      svg.append(svgEl("line", { class: "grid-line", x1: m.l, x2: W - m.r, y1: y(v), y2: y(v) }));
      svg.append(
        svgEl(
          "text",
          { class: "axis-label", x: m.l - 8, y: y(v) + 4, "text-anchor": "end" },
          fmtY(v)
        )
      );
    });
    [2000, 2005, 2010, 2015, 2020, 2025].forEach((yr) =>
      svg.append(
        svgEl(
          "text",
          { class: "axis-label", x: x(yr), y: H - m.b + 20, "text-anchor": "middle" },
          yr
        )
      )
    );
    const pts = (f) => Y.map((r) => `${x(r.year).toFixed(1)},${y(f(r)).toFixed(1)}`).join(" ");
    svg.append(svgEl("polyline", { class: "line-b", points: pts(b) }));
    svg.append(svgEl("polyline", { class: "line-a", points: pts(a) }));
    const lastR = Y.at(-1);
    const ya = y(a(lastR)),
      yb = y(b(lastR));
    const gapFix = Math.abs(ya - yb) < 16 ? 9 : 0;
    svg.append(
      svgEl(
        "text",
        {
          class: "end-label",
          x: W - m.r + 10,
          y: Math.min(ya, yb) === ya ? ya + 4 - gapFix : ya + 4 + gapFix,
        },
        labels[0](lastR)
      )
    );
    svg.append(
      svgEl(
        "text",
        {
          class: "end-label",
          x: W - m.r + 10,
          y: Math.min(ya, yb) === yb ? yb + 4 - gapFix : yb + 4 + gapFix,
        },
        labels[1](lastR)
      )
    );
    if (onDraw) onDraw({ x, y });
    // crosshair
    const hover = svgEl("g", { visibility: "hidden" });
    const hl = svgEl("line", { class: "hover-line", y1: m.t, y2: H - m.b });
    const da = svgEl("circle", { r: 4.5, fill: "var(--c-renew)" }),
      dbb = svgEl("circle", { r: 4.5, fill: "var(--c-compare)" });
    hover.append(hl, da, dbb);
    svg.append(hover);
    const hit = svgEl("rect", {
      class: "hit",
      x: m.l,
      y: m.t,
      width: W - m.l - m.r,
      height: H - m.t - m.b,
      tabindex: 0,
      "aria-label": "Chart data: use left and right arrow keys to move between years",
    });
    svg.append(hit);
    let cur = Y.length - 1;
    const show = (i) => {
      cur = Math.max(0, Math.min(Y.length - 1, i));
      const r = Y[cur],
        xx = x(r.year);
      hover.setAttribute("visibility", "visible");
      hl.setAttribute("x1", xx);
      hl.setAttribute("x2", xx);
      da.setAttribute("cx", xx);
      da.setAttribute("cy", y(a(r)));
      dbb.setAttribute("cx", xx);
      dbb.setAttribute("cy", y(b(r)));
      placeTip(tip, svg, W, xx, Math.min(y(a(r)), y(b(r))), tipHtml(r));
    };
    const hide = () => {
      hover.setAttribute("visibility", "hidden");
      tip.hidden = true;
    };
    hit.addEventListener("mousemove", (ev) => {
      const sr = svg.getBoundingClientRect();
      const vx = ((ev.clientX - sr.left) / sr.width) * W;
      show(Math.round(((vx - m.l) / (W - m.l - m.r)) * (Y.length - 1)));
    });
    hit.addEventListener("mouseleave", hide);
    hit.addEventListener("focus", () => show(cur));
    hit.addEventListener("blur", hide);
    hit.addEventListener("keydown", (ev) => {
      if (ev.key === "ArrowLeft" || ev.key === "ArrowRight") {
        ev.preventDefault();
        show(cur + (ev.key === "ArrowRight" ? 1 : -1));
      }
    });
  }

  /* ---------- 1. Crossover ---------- */
  lineChart({
    svg: $("#crossChart"),
    tip: $("#crossTip"),
    W: 760,
    H: 360,
    m: { t: 20, r: 150, b: 34, l: 44 },
    a: (r) => r.renewShare * 100,
    b: (r) => r.coalShare * 100,
    yMax: 50,
    yTicks: [0, 10, 20, 30, 40, 50],
    fmtY: (v) => v + "%",
    labels: [(r) => `Renewables ${pct(r.renewShare)}`, (r) => `Coal ${pct(r.coalShare)}`],
    tipHtml: (r) => `<b>${r.year}</b>Renewables ${pct(r.renewShare)} · Coal ${pct(r.coalShare)}`,
    onDraw: ({ x, y }) => {
      const svg = $("#crossChart");
      const pk = D.yearly.find((r) => r.year === D.peakCoalShare);
      svg.append(
        svgEl("circle", { class: "cross-dot", cx: x(pk.year), cy: y(pk.coalShare * 100), r: 4 })
      );
      svg.append(
        svgEl(
          "text",
          { class: "annot", x: x(pk.year), y: y(pk.coalShare * 100) - 12, "text-anchor": "middle" },
          `Coal peak ${pct(pk.coalShare)}, ${pk.year}`
        )
      );
      const cx = x(D.last),
        cy = y(L.renewShare * 100);
      svg.append(svgEl("line", { class: "annot-line", x1: cx, x2: cx - 70, y1: cy, y2: cy + 70 }));
      svg.append(
        svgEl(
          "text",
          { class: "annot", x: cx - 74, y: cy + 84, "text-anchor": "end" },
          `${D.last}: first year renewables > coal`
        )
      );
    },
  });

  /* ---------- 2. Yearly change (paired bars + total dot) ---------- */
  (() => {
    const svg = $("#changeChart"),
      tip = $("#changeTip");
    const W = 760,
      H = 380,
      m = { t: 20, r: 16, b: 34, l: 56 };
    const rows = Y.slice(1);
    const vals = rows.flatMap((r) => [r.dClean, r.dFossil, r.dTotal]);
    const lo = Math.floor(Math.min(...vals) / 500) * 500,
      hi = Math.ceil(Math.max(...vals) / 500) * 500;
    const band = (W - m.l - m.r) / rows.length;
    const y = (v) => m.t + ((hi - v) / (hi - lo)) * (H - m.t - m.b);
    for (let v = lo; v <= hi; v += 500) {
      svg.append(
        svgEl("line", {
          class: v === 0 ? "zero-line" : "grid-line",
          x1: m.l,
          x2: W - m.r,
          y1: y(v),
          y2: y(v),
        })
      );
      svg.append(
        svgEl(
          "text",
          { class: "axis-label", x: m.l - 8, y: y(v) + 4, "text-anchor": "end" },
          (v > 0 ? "+" : v < 0 ? "−" : "") + n0(Math.abs(v))
        )
      );
    }
    rows.forEach((r, i) => {
      const x0 = m.l + i * band,
        bw = Math.max(3, (band - 6) / 2),
        last = r.year === D.last;
      const bar = (v, cls, off) => {
        const top = Math.min(y(v), y(0)),
          h = Math.max(1, Math.abs(y(v) - y(0)));
        svg.append(
          svgEl("rect", {
            class: cls + (last ? "" : " bar-dim"),
            x: x0 + 2 + off,
            y: top,
            width: bw,
            height: h,
            rx: 2,
          })
        );
      };
      bar(r.dClean, "bar-a", 0);
      bar(r.dFossil, "bar-b", bw + 2);
      svg.append(
        svgEl("circle", {
          class: "total-dot",
          cx: x0 + band / 2,
          cy: y(r.dTotal),
          r: last ? 5 : 3.5,
        })
      );
      if (r.year % 5 === 0 || r.year === 2001)
        svg.append(
          svgEl(
            "text",
            { class: "axis-label", x: x0 + band / 2, y: H - m.b + 20, "text-anchor": "middle" },
            r.year
          )
        );
      const hit = svgEl("rect", {
        class: "hit",
        x: x0,
        y: m.t,
        width: band,
        height: H - m.t - m.b,
        tabindex: 0,
        "aria-label": `${r.year}: clean ${sgn(r.dClean)} TWh, fossil ${sgn(r.dFossil)} TWh, total ${sgn(r.dTotal)} TWh`,
      });
      const html = `<b>${r.year}</b>Clean ${sgn(r.dClean)} · Fossil ${sgn(r.dFossil)} · Total ${sgn(r.dTotal)} TWh`;
      const show = () =>
        placeTip(
          tip,
          svg,
          W,
          x0 + band / 2,
          Math.min(y(r.dClean), y(r.dTotal), y(r.dFossil)),
          html
        );
      hit.addEventListener("mouseenter", show);
      hit.addEventListener("focus", show);
      hit.addEventListener("mouseleave", () => (tip.hidden = true));
      hit.addEventListener("blur", () => (tip.hidden = true));
      svg.append(hit);
    });
    const lr = rows.at(-1),
      lx = m.l + (rows.length - 1) * band;
    // Label sits above every bar and dot, with a leader down to the 2025 bars
    const ly = y(hi) + 14,
      cx = lx + band / 2;
    svg.append(
      svgEl("line", { class: "annot-line", x1: cx, x2: cx, y1: ly + 6, y2: y(lr.dClean) - 8 })
    );
    svg.append(
      svgEl(
        "text",
        { class: "annot", x: cx, y: ly, "text-anchor": "end" },
        `${D.last}: clean ${sgn(lr.dClean)}, fossil ${sgn(lr.dFossil)}, demand ${sgn(lr.dTotal)} TWh`
      )
    );
  })();

  /* ---------- 3. Solar vs wind ---------- */
  lineChart({
    svg: $("#solarChart"),
    tip: $("#solarTip"),
    W: 520,
    H: 320,
    m: { t: 16, r: 110, b: 34, l: 50 },
    a: (r) => r.solar,
    b: (r) => r.wind,
    yMax: 3000,
    yTicks: [0, 1000, 2000, 3000],
    fmtY: (v) => n0(v),
    labels: [(r) => `Solar ${n0(r.solar)}`, (r) => `Wind ${n0(r.wind)}`],
    tipHtml: (r) => `<b>${r.year}</b>Solar ${n0(r.solar)} · Wind ${n0(r.wind)} TWh`,
  });

  /* ---------- 4. Mix dumbbells ---------- */
  const host = $("#mixRows");
  const max = Math.max(...D.mix.flatMap((m) => [m.share2000, m.share2025]));
  const sx = (v) => ((v / max) * 100).toFixed(2) + "%";
  [...D.mix]
    .sort((p, q) => q.share2025 - p.share2025)
    .forEach((m) => {
      const up = m.share2025 >= m.share2000;
      const row = document.createElement("div");
      row.className = "db " + (up ? "up" : "down");
      row.setAttribute("role", "listitem");
      row.setAttribute(
        "aria-label",
        `${m.source}: ${pct(m.share2000)} in 2000, ${pct(m.share2025)} in 2025`
      );
      const l = Math.min(m.share2000, m.share2025),
        r = Math.max(m.share2000, m.share2025);
      row.innerHTML = `<span>${m.source}<span class="grp">${m.group}</span></span><span class="rail" aria-hidden="true"><span class="seg" style="left:${sx(l)};width:calc(${sx(r)} - ${sx(l)})"></span><span class="dot" style="left:${sx(m.share2000)}"></span><span class="end" style="left:${sx(m.share2025)}"></span></span><span class="nums">${pct(m.share2000)} → <b>${pct(m.share2025)}</b></span>`;
      host.append(row);
    });

  // On narrow screens wide charts scroll inside their card: open them at the latest years
  document.querySelectorAll(".chart-wrap.scroll").forEach((w) => (w.scrollLeft = w.scrollWidth));

  if (window.upiMotion) window.upiMotion.ready();
})();
