// Samples Motion's (motion.dev) critically damped springs into a lookup table, so the composition uses
// Motion's exact curves without loading the library at render time (it calls performance.now()).
import { spring } from "motion";
import { writeFileSync } from "node:fs";
const out = {};
for (const d of [0.5, 0.8]) {
  const g = spring({ keyframes: [0, 1], visualDuration: d, bounce: 0 });
  const span = d * 2.5, n = 200;
  out[d] = { span, v: Array.from({ length: n + 1 }, (_, i) => +Math.min(1, g.next((i / n) * span * 1000).value).toFixed(5)) };
}
writeFileSync("assets/springs.js", "// Generated by tools/build-springs.mjs from motion@14.10.1 spring({ bounce: 0 }).\nwindow.EM_SPRINGS = " + JSON.stringify(out) + ";\n");
console.log("springs:", Object.keys(out).join(", "));
